// Helper utilities
export function getCountries(): CountryItem[] {
  return COUNTRIES;
}

export function getNationalities(): string[] {
  const nats = COUNTRIES.map(c => c.nationality).filter(Boolean);
  return Array.from(new Set(nats)).sort();
}

export function getStates(countryName: string): string[] {
  if (!countryName) return [];
  // Direct match or normalized lookup
  const key = Object.keys(STATES_BY_COUNTRY).find(
    k => k.toLowerCase() === countryName.trim().toLowerCase()
  );
  if (key) return STATES_BY_COUNTRY[key];
  return [];
}

export function getCities(stateName: string): string[] {
  if (!stateName) return [];
  const key = Object.keys(CITIES_BY_STATE).find(
    k => k.toLowerCase() === stateName.trim().toLowerCase()
  );
  if (key) return CITIES_BY_STATE[key];
  return [];
}
